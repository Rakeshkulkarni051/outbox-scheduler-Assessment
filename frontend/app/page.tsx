"use client";

import { useEffect } from "react";
import { useRouter } from "next/navigation";
import { signIn, useSession } from "next-auth/react";

export default function HomePage() {
  const { status } = useSession();
  const router = useRouter();

  useEffect(() => {
    if (status === "authenticated") {
      router.replace("/dashboard");
    }
  }, [status, router]);

  return (
    <main className="flex min-h-screen flex-col items-center justify-center bg-gray-50 px-4">
      <div className="w-full max-w-sm rounded-2xl border border-gray-200 bg-white p-8 shadow-sm">
        <h1 className="text-center text-2xl font-semibold text-gray-900">Login</h1>
        <p className="mt-1 text-center text-sm text-gray-500">
          Sign in to schedule and track your campaigns.
        </p>

        <button
          onClick={() => signIn("google", { callbackUrl: "/dashboard" })}
          disabled={status === "loading"}
          className="mt-6 flex w-full items-center justify-center gap-2 rounded-md border border-gray-300 bg-gray-50 px-4 py-2.5 text-sm font-medium text-gray-700 transition-colors hover:bg-gray-100 disabled:opacity-60"
        >
          <GoogleIcon />
          {status === "loading" ? "Checking session..." : "Login with Google"}
        </button>

        <p className="mt-6 text-center text-xs text-gray-400">
          Outbox Scheduler uses Google to verify who you are — no separate
          password required.
        </p>
      </div>
    </main>
  );
}

